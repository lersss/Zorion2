// Сегментная модель кривых R(X) компонент изменения населения (спека
// 99.2.17 §2/§5): узлы [{x, y}] + изгибы bends[] длиной len(nodes)−1.
// Математика сегмента: t = (x−x_i)/(x_{i+1}−x_i), t_k = (e^{k·t}−1)/(e^k−1),
// y = y_i + (y_{i+1}−y_i)·t_k. Экстраполяция за края — горизонтальная
// (константа крайнего узла). |k| ≤ 10. Дефолтные кривые — §3: стартовые
// наборы узлов = контрольные точки формул 99.2.12/99.2.13 (y узлов — точные
// значения формул в этих точках); bends подобраны так, что кривая держит
// контрольные точки и промежуточную сетку с допуском теста §9 (TestSegmentApproximation).
package settlement

import "math"

// bendTransform — bias-функция сегмента (§2): k = 0 → прямая (t),
// k > 0 → выпуклая (экспонента), k < 0 → вогнутая (логарифм).
// Устойчивость при k ≈ 0: порог 1e-10 (иначе 0/0 → NaN).
func bendTransform(t, k float64) float64 {
	if math.Abs(k) < 1e-10 {
		return t
	}
	return (math.Exp(k*t) - 1) / (math.Exp(k) - 1)
}

// evaluateCurve — значение сегментной кривой в точке x (§2/§5):
// экстраполяция за края — горизонтальная (константа крайнего узла);
// внутри — bias-интерполяция сегмента. Непрерывна по значению на узлах,
// монотонна внутри сегмента (t_k монотонен по t), не выходит за [y_i, y_{i+1}].
func evaluateCurve(nodes []SegmentNode, bends []float64, x float64) float64 {
	if x <= nodes[0].X {
		return nodes[0].Y // экстраполяция влево (горизонтальная)
	}
	if x >= nodes[len(nodes)-1].X {
		return nodes[len(nodes)-1].Y // вправо
	}
	for i := 0; i < len(bends); i++ {
		if x <= nodes[i+1].X {
			t := (x - nodes[i].X) / (nodes[i+1].X - nodes[i].X)
			return nodes[i].Y + (nodes[i+1].Y-nodes[i].Y)*bendTransform(t, bends[i])
		}
	}
	return nodes[len(nodes)-1].Y // safety, недостижимо
}

