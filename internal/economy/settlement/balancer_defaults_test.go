func TestSegmentApproximation(t *testing.T) {
	for comp, ref := range formulaRef {
		nodes, bends, ok := GetCurve(comp)
		if !ok {
			t.Fatalf("компонента %q недоступна в store", comp)
		}
		for x, want := range ref {
			got := evaluateCurve(nodes, bends, x)
			var tol float64
			if want > 1e-6 {
				tol = 0.05 * want
			} else {
				tol = 1e-6
			}
			if math.Abs(got-want) > tol {
				t.Errorf("%s(x=%v): R_кривая=%g, R_формула=%g — вне допуска %g", comp, x, got, want, tol)
			}
		}
	}
}
