// internal/names/ship_parts.go
// Имена деталей кораблей по категориям (спека 99.2.15 §3.3: name — из
// словаря имён категории, как имена регионов/веществ). Имя = корень +
// окончание; корни курируются вручную (как region.go), поэтому сочетания
// звучат по-человечески.
package names

import (
	"math/rand"
)

// shipPartRoots — корни имён деталей (категория → список).
var shipPartRoots = map[string][]string{
	"hull":   {"Стрел", "Клин", "Ланц", "Дрот", "Пил", "Верст", "Брус", "Стерж", "Вал", "Гран", "Щит", "Кол"},
	"nose":   {"Ост", "Шпил", "Игл", "Копь", "Рог", "Клюв", "Шип", "Пик", "Клин", "Нос", "Жал", "Бур"},
	"wings":  {"Крыл", "План", "Вейл", "Стре", "Взлёт", "Пар", "Ласт", "Весл", "Плеч", "Крой", "Разм", "Верш"},
	"engine": {"Гон", "Жар", "Сопл", "Тяг", "Плазм", "Вихр", "Драт", "Ядр", "Ион", "Факел", "Пыл", "Сгуст"},
	"tail":   {"Кил", "Хвост", "Плав", "Греб", "Стаб", "Рул", "Флаг", "Шток", "Лоп", "Крюк", "Пер", "Верт"},
}

// shipPartEndings — окончания имён деталей (созвучны корням).
var shipPartEndings = []string{
	"а", "ель", "ил", "он", "ун", "ей", "ант", "ер", "ин", "ак",
}

// GenerateShipPartName — имя детали категории от rng (детерминизм: тот же
// rng-поток → то же имя; пере-роллы дают разные имена при коллизиях нет —
// словарь не требует уникальности, но повторы маловероятны).
func GenerateShipPartName(category string, rng *rand.Rand) string {
	roots := shipPartRoots[category]
	if len(roots) == 0 {
		roots = shipPartRoots["hull"]
	}
	root := roots[rng.Intn(len(roots))]
	return root + shipPartEndings[rng.Intn(len(shipPartEndings))]
}