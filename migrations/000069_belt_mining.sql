-- Добыча в поясе (этап 3 поясов, спека
-- 2026-09-22-пояса-малых-тел-этап-3-добыча §4): запас пояса — конечный.
-- Владелец — пояс (запись system_belts); один запас на пояс (агрегат!).
-- Единица — тонны (масштаб трюма: 1 единица goods = 1 т при weight=1).
-- Запас — АБСТРАКЦИЯ «доступной фракции» (не масса пояса, ~10²¹ т): метроном
-- экономики (ГДД 10 §10.1), а не физика. Истощение — ИГРОВОЕ РЕШЕНИЕ создателя
-- 2026-09-22 (§10.1), НЕ эталон мира (FAQ не трогается).
-- Три состояния (см. §8.4):
--   NULL = «нет данных о запасе» (старый мир; бэкфилл запрещён, 41a);
--   0    = «выработан»;
--   > 0  = запас (уровень запаса).
-- Инициализация — ЛЕНИВАЯ (решение менеджера, выбор из §4): запас считается при
-- первом обращении (первый enter) как детерминированная функция composition.iron
-- и констант (reserve = 600·k_iron, k_iron = iron/0.30, §8.2). Генератор поясов
-- (planet_data_belt.go) НЕ трогается — поток RNG не сдвигается. NULL при этом
-- лениво инициализируется; ветка «нет данных» остаётся только на случай
-- отсутствия composition.iron (M19).
ALTER TABLE system_belts
    ADD COLUMN IF NOT EXISTS iron_remaining DOUBLE PRECISION
        CHECK (iron_remaining >= 0);

-- Выработан ⟺ iron_remaining = 0; «нет данных» ⟺ IS NULL. Отдельного флага нет.
