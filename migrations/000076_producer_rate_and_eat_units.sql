-- 000076_producer_rate_and_eat_units.sql — число скорости на паре
-- «постройка-подтип × рецепт» и единая единица нормы «ед/сутки/млрд»
-- (спека 2026-09-23-стадии-поселения-и-скорость-производства §9.1, итерация И1).
--
-- Номер 000076: проверено по рабочему дереву migrations/ (последний — 000075);
-- ловушка занятого номера — PITFALLS «БД и шелл».

-- Блок 1 — число скорости: NULL = «не объявлено» → постройка не производит.
-- Бэкфилла НЕТ (решение создателя 2026-09-23): существующие пары остаются NULL
-- (инертны до заполнения). Индексов не нужно — чтение идёт по producer_type_id
-- в составе существующего PK/пачки `= ANY($1)`.
ALTER TABLE producer_recipes ADD COLUMN rate DOUBLE PRECISION NULL
    CHECK (rate IS NULL OR rate >= 0);

-- Блок 2 — приведение норм потребления (params.eat) к единой единице модели
-- «ед/сутки/млрд»: коэффициент 24 × 1e9 = 2.4e10 (норма была «батч на особь в
-- час»). Признак params.eat_units отсекает повторную конверсию: условие и
-- запись признака — в одном UPDATE (идемпотентность по признаку, §2.5).
-- Исторические литералы 000067/000070 НЕ переписываются (§2.3): иначе на
-- свежей БД конверсия применилась бы к уже переведённому значению.
UPDATE producer_types
SET params = jsonb_set(
      jsonb_set(params, '{eat}', (
        SELECT jsonb_object_agg(k, to_jsonb((v::text)::numeric * 2.4e10))
        FROM jsonb_each_text(params->'eat') AS e(k, v)
      )),
      '{eat_units}', '"per_day_per_billion"'::jsonb)
WHERE params ? 'eat'
  AND COALESCE(params->>'eat_units', '') <> 'per_day_per_billion';
