-- 000078_belt_ice_remaining.sql
-- Добыча в поясе (этап 3, расширение): второй ресурс — лёд → «Вода неочищенная».
-- Владелец — пояс (запись system_belts); второй запас на пояс (агрегат).
-- Единица — тонны (масштаб трюма: 1 единица goods = 1 т при weight=1).
-- Запас — АБСТРАКЦИЯ «доступной фракции» (не масса пояса): метроном экономики
-- (ГДД 10 §10.1), ИГРОВОЕ РЕШЕНИЕ, НЕ эталон мира (FAQ не трогается, как 000069).
-- Три состояния (как iron_remaining):
--   NULL = ДВУСМЫСЛЕННО: «нет данных о льде» ИЛИ «льда в поясе нет»;
--   0    = «выработан»;
--   > 0  = запас льда.
-- Двусмысленность NULL намеренна и разрешается ТОЛЬКО через composition.ice:
--   composition.ice <= 0  → льда в поясе нет (NULL ожидаем, ледяных жил нет);
--   composition.ice >  0  → NULL = «нет данных» (старый мир, бэкфилл запрещён, 41a).
-- Отдельного флага/колонки «льда нет» не заводим (спека §10 п.7).
-- Инициализация — ЛЕНИВАЯ (как железо, 000069): при первом enter, если
-- composition.ice > 0, ice_remaining = 20000 (т, ВРЕМЕННО плоско — на тест,
-- спека §4/§18 п.1). Генератор поясов (planet_data_belt.go) НЕ трогается —
-- поток RNG этапа 1 не сдвигается.
ALTER TABLE system_belts
    ADD COLUMN IF NOT EXISTS ice_remaining DOUBLE PRECISION
        CHECK (ice_remaining >= 0);

-- Выработан ⟺ ice_remaining = 0; «нет данных/льда нет» ⟺ IS NULL.
