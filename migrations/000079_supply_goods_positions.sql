-- 000079_supply_goods_positions.sql — позиция потребления = ТОВАР: миграция
-- ключей params на всей ладдере ступеней класса «Поселение» + эффект «Жажда»
-- (спека 2026-09-24-потребление-по-товарам-и-альтернативы §6.2/§6.3/§8.2,
-- решения создателя 2026-09-24 О1–О6).
--
-- Номер 000079 забронирован менеджером (docs/COORDINATION.md); 000078 и 000080
-- заняты другими спеками (проверено по рабочему дереву, PITFALLS «БД и шелл»).
--
-- Правило резолва (§6.1): ключ params.eat/effects читается ТОЛЬКО как товар
-- (goods.name_norm); категория-«сахар» снята. Отсюда:
--   «продовольствие» (категория) → товар «пища»;
--   «вода» (категория kind=resource, мёртвый ключ) → удаляется (О6);
--   «пища» (была мёртвым ключом) → становится живым ключом нужды «голод»;
--   добавляется товар «очищенная вода» → нужда «жажда».
--
-- ⚠️ name_norm сравнивается ЛИТЕРАЛАМИ нижнего регистра, НЕ через lower():
-- коллация БД zorion = C, PostgreSQL lower() не конвертирует кириллицу
-- (docs/PITFALLS.md «БД и шелл», урок 000051). name_norm пишет Go
-- (graph.NormalizeName = strings.ToLower).
--
-- ⚠️ Вложенные eat/effects собираются слиянием `||` с объектом-обёрткой
-- (jsonb_build_object), НЕ jsonb_set: jsonb_set по отсутствующему
-- промежуточному объекту — молчаливый no-op (docs/PITFALLS.md, урок 000070).
-- Слияние `params || '{"eat": …}'` запрещено — затирает весь объект eat.
--
-- Ладдера резолвится ПО ДАННЫМ, не по именам ступеней (§6.3, правило спеки
-- стадий §4.3): предикат класса `params ? 'stage'` + parent_id типа-родителя
-- «Поселение». Список из семи имён пропустил бы будущую ступень (а одну
-- ступень однажды уже пропустили — «переставала пить»).

-- 1) Эффект «Жажда» — своя строка каталога, общая кривая 'hunger' (О3, §8.2):
-- отдельной компоненты Балансировки и правок админ-UI не заводим. Идемпотентно.
INSERT INTO effect_types (name, name_norm, impact, params)
VALUES ('Жажда', 'жажда', 'population_rate', '{"curve": "hunger"}')
ON CONFLICT (name_norm) DO NOTHING;

-- 2) Целевые params — на ВСЕЙ ладдере класса «Поселение» (7 ступеней).
--    Повторный прогон идемпотентен: те же ключи снимаются, те же значения
--    пишутся (миграция данных, не append); прочие ключи params (stage)
--    сохраняются слиянием.
WITH ladder AS (
    SELECT id FROM producer_types
    WHERE params ? 'stage'
      AND parent_id = (SELECT id FROM producer_types WHERE name_norm = 'поселение')
)
UPDATE producer_types pt
SET params = COALESCE(pt.params, '{}'::jsonb) || jsonb_build_object(
      'effects', COALESCE(pt.params->'effects', '{}'::jsonb)
                 - 'продовольствие'
                 || jsonb_build_object('пища', 'голод', 'очищенная вода', 'жажда'),
      'eat',     COALESCE(pt.params->'eat', '{}'::jsonb)
                 - 'вода' - 'продовольствие'
                 || jsonb_build_object('пища', 600, 'очищенная вода', 20000000),
      'eat_units', 'per_day_per_billion')
FROM ladder
WHERE pt.id = ladder.id;
