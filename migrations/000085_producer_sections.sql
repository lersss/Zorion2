-- 000085_producer_sections.sql — раздел вида постройки у типа-корня каталога
-- (спека 2026-09-25-студия-разделы-построек-по-видам §2/§3).
--
-- producer_types.section — свойство КАТАЛОГА, а не сравнение имён: раздел
-- интерфейса студии (Колонии/Фабрики/Лаборатории/Добывающие/Энергостанции).
-- Переименование типа-корня привязку к разделу не ломает (цель фичи).
--
-- Значения — открытый список интерфейса (colony/factory/lab/mining/energy);
-- CHECK НЕ ставится: новый раздел не должен требовать миграции (§2.2).
-- «Прочее» — виртуальный раздел клиента; значение other в БД не пишется.
-- Носитель — только тип-корень (parent_id IS NULL); у подтипов NULL
-- (раздел наследуется от корня, в БД не дублируется).
--
-- Идемпотентно: колонка IF NOT EXISTS; бэкфилл канон-корней — только по
-- name_norm (литералы нижнего регистра: lower() не работает с кириллицей при
-- collation C, см. docs/PITFALLS.md), только parent_id IS NULL и только
-- section IS NULL (повторный прогон — no-op). Корень с переименованным именем
-- остаётся NULL → «Прочее»; создатель назначает раздел в карточке.
--
-- Номер 000085 забронирован менеджером (docs/COORDINATION.md).

-- 1) Колонка раздела (TEXT NULL; CHECK не ставится — §2.2).
ALTER TABLE producer_types ADD COLUMN IF NOT EXISTS section TEXT;

-- 2) Бэкфилл канон-корней по name_norm: только типы-корни, только NULL.
UPDATE producer_types pt SET section = m.section
FROM (VALUES
    ('колония','colony'),
    ('фабрика','factory'),
    ('автофабрика','factory'),
    ('лаборатория','lab'),
    ('добывающая платформа','mining'),
    ('энергостанция','energy')
) AS m(name_norm, section)
WHERE pt.parent_id IS NULL AND pt.name_norm = m.name_norm AND pt.section IS NULL;
