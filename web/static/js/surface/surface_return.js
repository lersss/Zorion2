// Общий уход с прогулки на карту: «вызвать корабль» и смерть — один исход
// (спека высадки 2026-09-21 §6.3/И4 «много причин — один исход»).
// Одноразовый маркер `surfaceReturn` = id планеты прогулки читает карта
// (`map/data.js`) и открывает окно системы игрока с фокусом на этой планете —
// он вернулся на её орбиту. Маркер ставится здесь, в момент редиректа, а не при
// показе экрана смерти: игрок вправе закрыть вкладку, не нажав «продолжить», —
// маркер, поставленный заранее, остался бы висеть до следующего захода на карту.
export function returnToMap(planetId) {
    try { sessionStorage.setItem('surfaceReturn', String(planetId)); } catch (e) {}
    window.location.href = '/map';
}